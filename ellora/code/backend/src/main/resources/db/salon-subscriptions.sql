-- Additive, idempotent migration. Apply before starting this backend with Supabase ddl-auto:none.
-- All TIMESTAMP values below are Vietnam local time (Asia/Ho_Chi_Minh).
BEGIN;
CREATE TABLE IF NOT EXISTS public.salon_subscription_plans (
    tier VARCHAR(16) PRIMARY KEY CHECK (tier IN ('STANDARD','VIP')),
    monthly_price NUMERIC(15,0) CHECK (monthly_price >= 0),
    enabled BOOLEAN NOT NULL DEFAULT FALSE,
    updated_at TIMESTAMP,
    updated_by UUID,
    CONSTRAINT ck_salon_subscription_plan_price CHECK (NOT enabled OR monthly_price IS NOT NULL)
);
INSERT INTO public.salon_subscription_plans(tier,monthly_price,enabled)
VALUES ('STANDARD',NULL,FALSE),('VIP',NULL,FALSE) ON CONFLICT (tier) DO NOTHING;

ALTER TABLE public.salons ADD COLUMN IF NOT EXISTS subscription_tier VARCHAR(16);
ALTER TABLE public.salons ADD COLUMN IF NOT EXISTS subscription_starts_at TIMESTAMP;
ALTER TABLE public.salons ADD COLUMN IF NOT EXISTS subscription_expires_at TIMESTAMP;
DO $$ BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname='ck_salon_subscription_period' AND conrelid='public.salons'::regclass) THEN
        ALTER TABLE public.salons ADD CONSTRAINT ck_salon_subscription_period CHECK (
            (subscription_tier IS NULL AND subscription_starts_at IS NULL AND subscription_expires_at IS NULL)
            OR (subscription_tier IS NOT NULL AND subscription_tier IN ('STANDARD','VIP')
                AND subscription_starts_at IS NOT NULL AND subscription_expires_at IS NOT NULL
                AND subscription_expires_at > subscription_starts_at)
        );
    END IF;
END $$;

CREATE TABLE IF NOT EXISTS public.salon_subscription_requests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    salon_id BIGINT NOT NULL REFERENCES public.salons(id),
    tier VARCHAR(16) NOT NULL CHECK (tier IN ('STANDARD','VIP')),
    quoted_price NUMERIC(15,0) NOT NULL CHECK (quoted_price >= 0),
    status VARCHAR(16) NOT NULL CHECK (status IN ('PENDING','APPROVED','REJECTED')),
    created_at TIMESTAMP NOT NULL,
    reviewed_at TIMESTAMP,
    review_note VARCHAR(1000),
    reviewed_by UUID,
    starts_at TIMESTAMP,
    expires_at TIMESTAMP,
    CONSTRAINT ck_salon_subscription_request_decision CHECK (
        (status='PENDING' AND reviewed_at IS NULL AND reviewed_by IS NULL AND starts_at IS NULL AND expires_at IS NULL)
        OR (status='APPROVED' AND reviewed_at IS NOT NULL AND reviewed_by IS NOT NULL
            AND starts_at IS NOT NULL AND expires_at IS NOT NULL AND expires_at > starts_at)
        OR (status='REJECTED' AND reviewed_at IS NOT NULL AND reviewed_by IS NOT NULL
            AND review_note IS NOT NULL AND length(trim(review_note)) > 0 AND starts_at IS NULL AND expires_at IS NULL)
    )
);
CREATE UNIQUE INDEX IF NOT EXISTS uq_salon_subscription_pending ON public.salon_subscription_requests(salon_id) WHERE status='PENDING';
CREATE INDEX IF NOT EXISTS idx_salon_subscription_requests_status ON public.salon_subscription_requests(status,id);
CREATE INDEX IF NOT EXISTS idx_salon_subscription_requests_salon ON public.salon_subscription_requests(salon_id,id);
ALTER TABLE public.salon_subscription_plans ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.salon_subscription_requests ENABLE ROW LEVEL SECURITY;
-- No public RLS policies: all catalog reads and subscription mutations go through the backend.
COMMIT;
